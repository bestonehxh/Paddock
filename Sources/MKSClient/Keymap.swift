    // MARK: Text

    /// A printable character → keysym, for `MKSSession.sendText`. Latin-1 plus tab and newline;
    /// other scripts can't be typed through keysyms without a guest-side layout.
    public static func keysym(for c: Character) -> UInt32? {
        switch c {
        case "\n", "\r": return 0xFF0D
        case "\t": return 0xFF09
        default:
            guard c.unicodeScalars.count == 1, let scalar = c.unicodeScalars.first,
                  isLatin1Printable(scalar) else { return nil }
            return scalar.value
        }
    }

    /// Characters a US keyboard reaches only with Shift held. A bare keysym for "H" or "!"
    /// is legal RFB, but Windows guests type the unshifted key for it, so `keyEvents(for:)`
    /// wraps these in Shift_L.
    static let usShiftedPunctuation: Set<Character> = ["~", "!", "@", "#", "$", "%", "^", "&", "*", "(", ")",
                                                       "_", "+", "{", "}", "|", ":", "\"", "<", ">", "?"]

    public static func needsShift(_ c: Character) -> Bool {
        if usShiftedPunctuation.contains(c) { return true }
        guard c.unicodeScalars.count == 1, let scalar = c.unicodeScalars.first else { return false }
        return (0x41...0x5A).contains(scalar.value)   // A–Z
    }

    /// One key event: keysym and press / release.
    public struct KeyEvent: Sendable, Equatable {
        public var keysym: UInt32
        public var down: Bool
        public init(keysym: UInt32, down: Bool) { self.keysym = keysym; self.down = down }
    }

    /// Text → ordered key events (down/up per character, shifted characters wrapped in
    /// Shift_L down/up); `skipped` holds the characters that have no keysym.
    public static func keyEvents(for text: String) -> (events: [KeyEvent], skipped: [Character]) {
        var events: [KeyEvent] = []
        var skipped: [Character] = []
        for c in text {
            guard let k = keysym(for: c) else { skipped.append(c); continue }
            let shifted = needsShift(c)
            if shifted { events.append(KeyEvent(keysym: shift, down: true)) }
            events.append(KeyEvent(keysym: k, down: true))
            events.append(KeyEvent(keysym: k, down: false))
            if shifted { events.append(KeyEvent(keysym: shift, down: false)) }
        }
        return (events, skipped)
    }
