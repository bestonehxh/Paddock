    /// macOS key code + characters → X11 keysym.
    ///
    /// A single printable Latin-1 character wins — that is what the layout actually typed, which
    /// keeps non-US layouts working; otherwise the US table. Modifiers always map by key code.
    public static func keysym(keyCode: UInt16, characters: String?) -> UInt32? {
        if modifierKeyCodes.contains(keyCode) { return byKeyCode[keyCode] }
        if let characters, characters.unicodeScalars.count == 1,
           let scalar = characters.unicodeScalars.first, isLatin1Printable(scalar) {
            return scalar.value
        }
        return byKeyCode[keyCode]
    }

    static func isLatin1Printable(_ scalar: Unicode.Scalar) -> Bool {
        (0x20...0x7E).contains(scalar.value) || (0xA0...0xFF).contains(scalar.value)
    }

